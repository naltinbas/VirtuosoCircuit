function trackEntry(def: TrackDefinition): ManifestEntry {
  const m = def.metadata;
  const entry: ManifestEntry = {
    asset: `${m.title} (${m.id})`,
    composer: m.catalogNumber ? `${m.composer}, ${m.catalogNumber}` : m.composer,
    compositionStatus: COMPOSITION_STATUS,
    arrangementSource: ARRANGEMENT_SOURCE,
    audioSource: AUDIO_SOURCE,
    licenseRationale: m.licenseNotes,
    // Public-domain compositions carry no legal attribution duty; the credits
    // name the composer anyway because it is the honest thing to print.
    attributionRequired: false,
    sourceNote: m.scoreSourceCredit,
  };
  if (m.attributionNote !== undefined) entry.attributionNote = m.attributionNote;
  return entry;
}

export function buildManifest(defs: readonly TrackDefinition[]): ManifestEntry[] {
  const tracks = [...defs].sort((a, b) => a.metadata.order - b.metadata.order).map(trackEntry);
  return [...tracks, ...NON_TRACK_ENTRIES];
}

