// Where every piece of content in the game comes from.
//
// The game ships no third-party files: the music is synthesized at runtime
// from note data written for this project, the interface sounds are
// oscillators, the icon is hand-drawn SVG and the text is set in whatever the
// player's system already has. The manifest states that per asset so the
// credits screen and ATTRIBUTION_AND_LICENSES.md can be generated from one
// list rather than kept in step by hand.

import type { TrackDefinition } from "../charts/ChartTypes";

export interface ManifestEntry {
  /** What the row is about, e.g. a track title with its id, or a file path. */
  asset: string;
  composer: string;
  /** Standing of the underlying composition, never of a performance. */
  compositionStatus: string;
  /** Where the note data being played came from. */
  arrangementSource: string;
  /** How sound is produced for it. */
  audioSource: string;
  licenseRationale: string;
  attributionRequired: boolean;
  /** Caveats worth printing, such as a work long credited to the wrong composer. */
  attributionNote?: string;
  /** The edition or reference the arrangement was written from. */
  sourceNote: string;
}

export const COMPOSITION_STATUS = "Public-domain composition";

export const ARRANGEMENT_SOURCE =
  "Original game arrangement based on a public-domain composition (project note-event data, no external MIDI)";

export const AUDIO_SOURCE = "Web Audio synthesis at runtime";

const NOT_APPLICABLE = "Not applicable";

